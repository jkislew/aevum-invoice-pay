// Generate app/config.js from artifacts + deployment.json (run after deploy).
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const artifact = JSON.parse(readFileSync(new URL("../artifacts/InvoicePay.json", import.meta.url), "utf8"));
const depFile = new URL("../deployment.json", import.meta.url);
const dep = existsSync(depFile) ? JSON.parse(readFileSync(depFile, "utf8")) : null;

const config = {
  chainId: 44005,
  chainIdHex: "0xABE5",
  chainName: "QDay Aevum Testnet",
  rpc: "https://rpc-test.qday.info",
  explorer: "https://explorer-test.qday.info",
  tusd8: "0x456569838f1d43009A91ebA4263147Afd7233483",
  invoicePay: dep ? dep.invoicePay : "",
  invoicePayAbi: artifact.abi,
};
writeFileSync(
  new URL("../app/config.js", import.meta.url),
  "// Generated by scripts/build-app-config.mjs — do not edit by hand.\nwindow.AEVUM_CONFIG = " + JSON.stringify(config, null, 2) + ";\n"
);
console.log("app/config.js written; invoicePay =", config.invoicePay || "(not deployed yet)");
